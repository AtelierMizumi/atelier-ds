// Build dist/: tokens -> CSS custom properties, concat base + components, copy JS and tokens.
// No dependencies. Run: node scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const tokens = JSON.parse(read('tokens/tokens.json'));
const { core, semantic, themes } = tokens;

const lines = [];
const decl = (prefix, obj) => Object.entries(obj).filter(([k]) => !k.startsWith('$'))
  .forEach(([k, v]) => lines.push(`  --ds-${prefix}${k}: ${v};`));

lines.push(':root {');
decl('', core.color);
decl('font-', core.font);
decl('size-', core.size);
decl('space-', core.space);
decl('shape-', core.shape);
decl('layout-', core.layout);
decl('motion-', core.motion);
decl('z-', core.z);
for (const [k, ref] of Object.entries(semantic)) lines.push(`  --ds-${k}: var(--ds-${ref});`);
lines.push('}');

for (const [name, t] of Object.entries(themes)) {
  if (!t.color) continue;
  lines.push(`[data-ds-theme="${name}"] {`);
  decl('', t.color);
  // semantic aliases are re-declared so they resolve against the theme's colors on this element
  for (const [k, ref] of Object.entries(semantic)) lines.push(`  --ds-${k}: var(--ds-${ref});`);
  lines.push('}');
}

const banner = `/* Atelier DS v${tokens.version}. Generated by scripts/build.mjs from tokens/tokens.json. Do not edit dist/. */\n`;
const out = [
  banner,
  '@layer ds-tokens, ds-base, ds-components;',
  `@layer ds-tokens {\n${lines.join('\n')}\n}`,
  read('src/css/base.css'),
  read('src/css/components.css'),
].join('\n');

const dist = new URL('dist/', root);
rmSync(dist, { recursive: true, force: true });
mkdirSync(new URL('js/', dist), { recursive: true });
writeFileSync(new URL('atelier-ds.css', dist), out);
cpSync(new URL('src/js/', root), new URL('js/', dist), { recursive: true });
writeFileSync(new URL('tokens.json', dist), JSON.stringify(tokens, null, 2));
writeFileSync(new URL('VERSION', dist), `${tokens.version}\n`);
console.log(`atelier-ds ${tokens.version}: dist/atelier-ds.css ${out.length} bytes`);
